-- ============================================================
-- einblick WMS - Phase 1 DB 스키마 (PostgreSQL)
-- Oracle 23ai 스키마(einblick_schema_oracle.sql)에서 마이그레이션됨
-- ============================================================

CREATE TABLE users (
                       user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name            VARCHAR(50)  NOT NULL,
                       login_id        VARCHAR(50)  NOT NULL UNIQUE,
                       password        VARCHAR(255) NOT NULL,
                       role            VARCHAR(20) DEFAULT 'STAFF' NOT NULL
                           CHECK (role IN ('STAFF','MANAGER','DIRECTOR','ADMIN')),
                       brand_scope     VARCHAR(200),
                       approval_level  INTEGER DEFAULT 0,
                       created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                       updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE customers (
                           customer_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           code            VARCHAR(30) NOT NULL UNIQUE,
                           name            VARCHAR(100) NOT NULL,
                           is_house_alias  BOOLEAN DEFAULT FALSE NOT NULL,
                           packing_method  VARCHAR(60),
                           format          VARCHAR(100),
                           assort_solid    VARCHAR(30),
                           std_ratio       VARCHAR(50),
                           std_polybag     VARCHAR(20),
                           std_carton      VARCHAR(20),
                           std_hanger      VARCHAR(300),
                           created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE programs (
                          program_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          brand           VARCHAR(50) NOT NULL,
                          league          VARCHAR(50),
                          style_code      VARCHAR(50) NOT NULL,
                          style_name      VARCHAR(200),
                          season          VARCHAR(30),
                          created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                          CONSTRAINT uq_program_style_season UNIQUE (style_code, season)
);

CREATE TABLE purchase_orders (
                                 po_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 po_number        VARCHAR(30) NOT NULL UNIQUE,
                                 program_id       BIGINT NOT NULL,
                                 customer_id      BIGINT NOT NULL,
                                 dlvy_date        DATE,
                                 transport_method VARCHAR(20) DEFAULT 'UNASSIGNED' NOT NULL
                                     CHECK (transport_method IN ('AIR','BOAT','SPLIT','UNASSIGNED')),
                                 status           VARCHAR(20) DEFAULT 'RECEIVED' NOT NULL
                                     CHECK (status IN ('RECEIVED','IN_REVIEW','RECONCILED','MISMATCH','SHIPPED','CLOSED')),
                                 original_pdf_url VARCHAR(500),
                                 total_qty        INTEGER DEFAULT 0 NOT NULL,
                                 created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                                 updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                                 CONSTRAINT fk_po_program  FOREIGN KEY (program_id)  REFERENCES programs(program_id),
                                 CONSTRAINT fk_po_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

CREATE TABLE po_history (
                            history_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            po_id           BIGINT NOT NULL,
                            user_id         BIGINT NOT NULL,
                            field_changed   VARCHAR(50),
                            old_value       VARCHAR(200),
                            new_value       VARCHAR(200),
                            comment         VARCHAR(500),
                            created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                            CONSTRAINT fk_pohist_po   FOREIGN KEY (po_id)   REFERENCES purchase_orders(po_id),
                            CONSTRAINT fk_pohist_user FOREIGN KEY (user_id) REFERENCES users(user_id)
);

CREATE TABLE po_lines (
                          po_line_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          po_id           BIGINT NOT NULL,
                          team            VARCHAR(100),
                          player          VARCHAR(100),
                          total_qty       INTEGER DEFAULT 0 NOT NULL,
                          carton_qty      INTEGER,
                          CONSTRAINT fk_poline_po FOREIGN KEY (po_id) REFERENCES purchase_orders(po_id)
);

CREATE TABLE po_line_sizes (
                               po_line_size_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               po_line_id      BIGINT NOT NULL,
                               size_code       VARCHAR(10) NOT NULL,
                               qty             INTEGER DEFAULT 0 NOT NULL,
                               CONSTRAINT fk_polinesize_line FOREIGN KEY (po_line_id) REFERENCES po_lines(po_line_id),
                               CONSTRAINT uq_poline_size UNIQUE (po_line_id, size_code)
);

CREATE TABLE assorts (
                         assort_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         program_id      BIGINT NOT NULL,
                         team            VARCHAR(100),
                         player          VARCHAR(100),
                         customer_label  VARCHAR(50) NOT NULL,
                         assort_solid    VARCHAR(30),
                         ratio           VARCHAR(50),
                         polybag         VARCHAR(20),
                         carton          VARCHAR(20),
                         hanger          VARCHAR(300),
                         total_qty       INTEGER DEFAULT 0 NOT NULL,
                         source_file     VARCHAR(300),
                         created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                         CONSTRAINT fk_assort_program FOREIGN KEY (program_id) REFERENCES programs(program_id)
);

CREATE TABLE assort_sizes (
                              assort_size_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              assort_id       BIGINT NOT NULL,
                              size_code       VARCHAR(10) NOT NULL,
                              qty             INTEGER DEFAULT 0 NOT NULL,
                              CONSTRAINT fk_assortsize_assort FOREIGN KEY (assort_id) REFERENCES assorts(assort_id),
                              CONSTRAINT uq_assort_size UNIQUE (assort_id, size_code)
);

CREATE TABLE reconciliation_results (
                                        reconciliation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        po_line_id       BIGINT,
                                        assort_id        BIGINT,
                                        diff_qty         INTEGER DEFAULT 0 NOT NULL,
                                        status           VARCHAR(20) NOT NULL
                                            CHECK (status IN ('OK','MISSING_IN_ASSORT','MISSING_IN_PO','QTY_MISMATCH','NEEDS_REVIEW')),
                                        is_house_matched BOOLEAN DEFAULT FALSE NOT NULL,
                                        note             VARCHAR(500),
                                        checked_by       BIGINT,
                                        checked_at       TIMESTAMP,
                                        created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                                        CONSTRAINT fk_recon_poline FOREIGN KEY (po_line_id) REFERENCES po_lines(po_line_id),
                                        CONSTRAINT fk_recon_assort FOREIGN KEY (assort_id)  REFERENCES assorts(assort_id),
                                        CONSTRAINT fk_recon_user   FOREIGN KEY (checked_by) REFERENCES users(user_id)
);

-- ============================================================
-- Phase 2~4용 최소 테이블
