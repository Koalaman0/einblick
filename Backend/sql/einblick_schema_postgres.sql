CREATE TABLE samples (
                         sample_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         program_id      BIGINT NOT NULL,
                         type            VARCHAR(20) NOT NULL
                             CHECK (type IN ('SMS','FIT','APPROVAL','TOP','GB_TEST','WALMART_TEST','CNS_TEST')),
                         status           VARCHAR(20) DEFAULT 'PREPARING' NOT NULL
                             CHECK (status IN ('PREPARING','SENT','COMMENT_WAIT','APPROVED','FAIL')),
                         comment_source  VARCHAR(50),
                         due_date        DATE,
                         created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                         CONSTRAINT fk_sample_program FOREIGN KEY (program_id) REFERENCES programs(program_id)
);

CREATE TABLE vendors (
                         vendor_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         name            VARCHAR(100) NOT NULL,
                         is_overseas     BOOLEAN DEFAULT FALSE NOT NULL,
                         contact_name    VARCHAR(50),
                         contact_info    VARCHAR(200)
);

CREATE TABLE material_orders (
                                 material_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 program_id       BIGINT NOT NULL,
                                 vendor_id        BIGINT NOT NULL,
                                 item             VARCHAR(200),
                                 qty              INTEGER,
                                 amount           NUMERIC(14,2),
                                 approval_status  VARCHAR(20) DEFAULT 'DRAFT' NOT NULL
                                     CHECK (approval_status IN ('DRAFT','MANAGER_REVIEW','DIRECTOR_REVIEW','APPROVED','REJECTED')),
                                 wire_status      VARCHAR(20) DEFAULT 'NOT_SENT' NOT NULL
                                     CHECK (wire_status IN ('NOT_SENT','WIRED','CONFIRMED')),
                                 transport_method VARCHAR(20) CHECK (transport_method IN ('AIR','BOAT','FEDEX')),
                                 created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                                 CONSTRAINT fk_matorder_program FOREIGN KEY (program_id) REFERENCES programs(program_id),
                                 CONSTRAINT fk_matorder_vendor  FOREIGN KEY (vendor_id)  REFERENCES vendors(vendor_id)
);

CREATE TABLE packing_methods (
                                 packing_method_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 customer_id      BIGINT NOT NULL,
                                 ppk_type         VARCHAR(10) NOT NULL CHECK (ppk_type IN ('SOLID','ASSORT')),
                                 ratio            VARCHAR(50),
                                 sticker_types    VARCHAR(100),
                                 CONSTRAINT fk_packing_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

CREATE TABLE sticker_requests (
                                  sticker_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  po_id            BIGINT NOT NULL,
                                  sticker_type     VARCHAR(10) NOT NULL CHECK (sticker_type IN ('UPC','PRN','LPN')),
                                  qty              INTEGER,
                                  loss_rate        NUMERIC(4,2) DEFAULT 1.00,
                                  status           VARCHAR(20) DEFAULT 'REQUESTED' NOT NULL
                                      CHECK (status IN ('REQUESTED','SENT_TO_FACTORY','CONFIRMED')),
                                  CONSTRAINT fk_sticker_po FOREIGN KEY (po_id) REFERENCES purchase_orders(po_id)
);

CREATE TABLE shipping_rules (
                                shipping_rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                program_id       BIGINT NOT NULL,
                                season           VARCHAR(30),
                                po_range_from    VARCHAR(30),
                                po_range_to      VARCHAR(30),
                                transport_method VARCHAR(20) NOT NULL CHECK (transport_method IN ('AIR_ONLY','BOAT_ONLY','SPLIT')),
                                ex_factory_date  DATE,
                                CONSTRAINT fk_shiprule_program FOREIGN KEY (program_id) REFERENCES programs(program_id)
);

-- TECH PACK / ARTWORK 파일 관리 (파일 본문은 BYTEA로 DB에 직접 저장)
CREATE TABLE tech_pack_files (
                                  file_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  program_id   BIGINT NOT NULL,
                                  file_name    VARCHAR(255) NOT NULL,
                                  file_type    VARCHAR(20) NOT NULL CHECK (file_type IN ('TECH_PACK','ARTWORK')),
                                  content_type VARCHAR(100),
                                  file_size    BIGINT NOT NULL,
                                  file_data    BYTEA NOT NULL,
                                  status       VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS'
                                      CHECK (status IN ('IN_PROGRESS','IN_REVIEW','APPROVED')),
                                  uploaded_by  BIGINT,
                                  created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  updated_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  CONSTRAINT fk_techpack_program FOREIGN KEY (program_id) REFERENCES programs(program_id),
                                  CONSTRAINT fk_techpack_user FOREIGN KEY (uploaded_by) REFERENCES users(user_id)
);

